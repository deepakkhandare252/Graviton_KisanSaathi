package com.kisanscheme.saathi.model;

/**
 * 9 Standardized user-reported application statuses.
 * Disclaimer: All application statuses are farmer-reported and track preparation;
 * official approvals are issued exclusively by authorized government departments.
 */
public enum ApplicationStatus {
    INTERESTED,
    PREPARING,
    READY_TO_APPLY,
    APPLIED,
    UNDER_REVIEW,
    APPROVED,
    REJECTED,
    NEEDS_CORRECTION,
    WITHDRAWN
}
